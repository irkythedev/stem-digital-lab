import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { imageV } from '../src/labs/physics/lens-core.ts';
import { ELEMENTS } from '../src/lib/elements.ts';
import { TYPICAL_COMPOUNDS } from '../src/lib/chemistry/valency.ts';
import { formatMass, molarMass } from '../src/lib/chemistry/formula-core.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export interface Bi {
  zh: string;
  en: string;
}

export interface DataTable {
  caption: Bi;
  columns: Bi[];
  rows: Bi[][];
}

const bi = (zh: string, en: string): Bi => ({ zh, en });
const num = (n: number, digits = 1): Bi => {
  const s = n.toFixed(digits);
  return bi(s, s);
};

/** 与 Lens.tsx 的 imageDesc 保持同一判据（f=10 cm）。 */
const LENS_F = 10;
const LENS_SAMPLES = [30, 25, 20, 15, 12, 10, 8, 5];

function lensCase(u: number, f: number): { range: Bi; nature: Bi; app: Bi } {
  if (Math.abs(u - 2 * f) < 1e-9) {
    return {
      range: bi('u = 2f', 'u = 2f'),
      nature: bi('倒立、等大、实像', 'Inverted, same size, real'),
      app: bi('测量焦距', 'Focal-length measurement'),
    };
  }
  if (u > 2 * f) {
    return {
      range: bi('u > 2f', 'u > 2f'),
      nature: bi('倒立、缩小、实像', 'Inverted, reduced, real'),
      app: bi('照相机', 'Camera'),
    };
  }
  if (Math.abs(u - f) < 1e-9) {
    return {
      range: bi('u = f', 'u = f'),
      nature: bi('不成清晰像（出射光平行）', 'No sharp image (emergent rays are parallel)'),
      app: bi('测焦距边界', 'Boundary case for focal length'),
    };
  }
  if (u > f) {
    return {
      range: bi('f < u < 2f', 'f < u < 2f'),
      nature: bi('倒立、放大、实像', 'Inverted, magnified, real'),
      app: bi('投影仪、幻灯机', 'Projector, slide projector'),
    };
  }
  return {
    range: bi('u < f', 'u < f'),
    nature: bi('正立、放大、虚像', 'Upright, magnified, virtual'),
    app: bi('放大镜', 'Magnifier'),
  };
}

/** 由计算核生成凸透镜五类成像真值表；不读任何手写数值。 */
export function buildLensDataTable(): DataTable {
  const rows: Bi[][] = LENS_SAMPLES.map((u) => {
    const v = imageV(u, LENS_F);
    const c = lensCase(u, LENS_F);
    const uCell = bi(`${u.toFixed(1)}（${c.range.zh}）`, `${u.toFixed(1)} (${c.range.en})`);
    if (v === null) {
      return [uCell, bi('—', '—'), bi('—', '—'), c.nature, c.app];
    }
    const mag = Math.abs(v / u);
    return [uCell, num(v), num(mag, 2), c.nature, c.app];
  });

  return {
    caption: bi(
      `焦距 f = ${LENS_F.toFixed(1)} cm 时物距与成像性质对照表（由 lens-core 计算生成）`,
      `Object distance and image properties for f = ${LENS_F.toFixed(1)} cm (generated by lens-core)`,
    ),
    columns: [
      bi('物距 u（cm）', 'Object distance u (cm)'),
      bi('像距 v（cm）', 'Image distance v (cm)'),
      bi('放大率 |v/u|', 'Magnification |v/u|'),
      bi('像的性质', 'Image properties'),
      bi('对应应用', 'Application'),
    ],
    rows,
  };
}

const CAT: Record<string, Bi> = {
  metal: bi('金属', 'Metal'),
  nonmetal: bi('非金属', 'Non-metal'),
  noble: bi('稀有气体', 'Noble gas'),
  metalloid: bi('类金属', 'Metalloid'),
};

/** 由 118 元素数据生成前 20 号元素速查表。 */
export function buildPeriodicDataTable(): DataTable {
  const rows: Bi[][] = ELEMENTS.filter((e) => e.n <= 20).map((e) => {
    const outer = e.shells.at(-1) ?? 0;
    const mass = e.mass === null ? '—' : String(e.mass);
    return [
      bi(String(e.n), String(e.n)),
      bi(e.symbol, e.symbol),
      bi(e.zh, e.en),
      bi(mass, mass),
      CAT[e.cat],
      bi(String(outer), String(outer)),
    ];
  });

  return {
    caption: bi(
      '前 20 号元素速查表（原子序数、符号、名称、相对原子质量、类别、最外层电子数）',
      'First 20 elements quick reference (atomic number, symbol, name, relative atomic mass, category, valence electrons)',
    ),
    columns: [
      bi('原子序数', 'Atomic number'),
      bi('符号', 'Symbol'),
      bi('中文名', 'Chinese name'),
      bi('相对原子质量', 'Relative atomic mass'),
      bi('类别', 'Category'),
      bi('最外层电子数', 'Valence electrons'),
    ],
    rows,
  };
}

/** 由初中常见物质库与 formula-core 生成化学式速查表；相对分子质量不接受手写。 */
export function buildChemistryDataTable(): DataTable {
  const rows: Bi[][] = TYPICAL_COMPOUNDS.map((c) => {
    const mass = molarMass(c.formula);
    const massText = mass === null ? '—' : formatMass(mass);
    return [
      bi(c.formula, c.formula),
      c.name,
      c.category,
      bi(massText, massText),
      c.note ?? bi('—', '—'),
    ];
  });

  return {
    caption: bi(
      '初中常见物质速查表（化学式、名称、类别、相对分子质量与要点；由 formula-core 计算生成）',
      'Common junior-high compounds (formula, name, category, relative molecular mass and key note; generated by formula-core)',
    ),
    columns: [
      bi('化学式', 'Formula'),
      bi('名称', 'Name'),
      bi('类别', 'Category'),
      bi('相对分子质量', 'Relative molecular mass'),
      bi('要点', 'Key note'),
    ],
    rows,
  };
}

const FILES: Array<[string, () => DataTable]> = [
  ['content/labs/lens.json', buildLensDataTable],
  ['content/tools/periodic-table.json', buildPeriodicDataTable],
  ['content/tools/chemistry-formulas.json', buildChemistryDataTable],
];

export function expectedTables(): Map<string, DataTable> {
  return new Map(FILES.map(([file, build]) => [file, build()]));
}

const write = process.argv.includes('--write');
const invokedDirectly =
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === join(process.argv[1]);

if (invokedDirectly) {
  for (const [rel, build] of FILES) {
    const table = build();
    if (write) {
      const path = join(ROOT, rel);
      const json = JSON.parse(readFileSync(path, 'utf8')) as Record<string, unknown>;
      json.dataTable = table;
      writeFileSync(path, JSON.stringify(json, null, 2) + '\n', 'utf8');
      console.log(`✓ 已写入 ${rel}：${table.rows.length} 行`);
    } else {
      console.log(`— ${rel}`);
      console.log(JSON.stringify(table, null, 2));
    }
  }
}
