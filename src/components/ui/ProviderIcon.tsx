/**
 * 服务商 id → 品牌标 key。
 *
 * 为什么不直接用 id 查表：id 是**对外契约**（存进 localStorage 的 `providerId`，改了会让老用户的
 * 配置失效），所以它保留 dashscope / moonshot / volcengine 这些平台侧名字；而品牌标要按
 * 「这家对外叫什么」来认（qwen / kimi / doubao）。两者必须显式映射——
 * 少一处映射的后果是静默退化成插头占位符，界面看起来"有图标"，只是全是同一个插头。
 */
export const PROVIDER_ICON_KEY: Record<string, ProviderIconId> = {
  deepseek: 'deepseek',
  dashscope: 'qwen',
  moonshot: 'kimi',
  zhipu: 'zhipu',
  volcengine: 'doubao',
};

interface ProviderIconProps {
  id: string;
  /** 尺寸与颜色类；默认 16px，颜色继承 currentColor */
  className?: string;
}

export default function ProviderIcon({ id, className = 'h-4 w-4' }: ProviderIconProps) {
  const key = PROVIDER_ICON_KEY[id];
  const ds = key ? PROVIDER_PATHS[key] : null;
  if (!ds) {
    // 自定义端点：无品牌标，用插头指认「这是一根线，不是一家厂商」
    return <Plug className={className} aria-hidden="true" />;
  }
  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      className={className}
      aria-hidden="true"
      focusable="false"
    >
      {ds.map((d) => (
        <path key={d.slice(0, 24)} d={d} />
      ))}
    </svg>
  );
}
